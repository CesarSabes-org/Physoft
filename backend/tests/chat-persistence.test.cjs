const { test } = require('node:test')
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const { PrismaClient } = require('@prisma/client')
const express = require('express')
const jwt = require('jsonwebtoken')
const { ChatRepository } = require('../dist/infrastructure/repositories/ChatRepository')
const { ChatService } = require('../dist/application/services/chat/ChatService')
const { ConversationService } = require('../dist/application/services/chat/ConversationService')
const { createChatRouter } = require('../dist/presentation/routes/chatRoutes')
const url = process.env.TEST_DATABASE_URL
if (url) {
  const target = new URL(url)
  if (!['127.0.0.1', 'localhost'].includes(target.hostname) || target.pathname !== '/physoft_chat_tests') throw new Error('Tests require an isolated local physoft_chat_tests database')
}
test('persistent conversations: ownership, history, retries, locking and HTTP contracts', { skip: !url }, async t => {
  const db = new PrismaClient({ datasources: { db: { url } }, log: [] })
  const user = await db.user.create({ data: { email: `${randomUUID()}@example.invalid`, passwordHash: 'synthetic' } })
  t.after(async () => { await db.user.delete({ where: { id: user.id } }); await db.$disconnect() })
  const repository = new ChatRepository(db)
  const id = randomUUID()
  const conversation = await repository.create(user.id, id, 'explain_concepts')
  assert.equal(conversation.turns.length, 0)
  await assert.rejects(repository.get('other-user', id), e => e.status === 404)
  await assert.rejects(repository.delete('other-user', id), e => e.status === 404)
  assert.deepEqual(await repository.list('other-user'), [])
  await assert.rejects(repository.create(user.id, id, 'general'), e => e.code === 'FOCUS_LOCKED')
  const calls = []
  const service = new ConversationService(repository, new ChatService({ generate: async (system, messages) => { calls.push({system,messages}); return { content:'Saved answer', truncated:false } } }))
  const requestId = randomUUID()
  await service.reply(user.id, id, requestId, 'Strength?', new AbortController().signal)
  await service.reply(user.id, id, requestId, 'Strength?', new AbortController().signal)
  assert.equal(calls.length, 1)
  await service.reply(user.id, id, randomUUID(), 'And power?', new AbortController().signal)
  assert.equal(calls[1].messages.length, 3)
  assert.equal(calls[0].system, calls[1].system)
  assert.equal((await new ChatRepository(db).get(user.id, id)).turns.length, 2)
  const pendingId = randomUUID()
  const first = await repository.begin(user.id, id, pendingId, 'Recovery?')
  await assert.rejects(repository.begin(user.id, id, randomUUID(), 'Concurrent?'), e => e.code === 'CHAT_BUSY')
  await db.chatTurn.update({where:{id:first.turn.id},data:{leaseExpiresAt:new Date(0)}})
  assert.equal((await repository.get(user.id,id)).turns.at(-1).status,'failed')
  const retry = await repository.begin(user.id,id,pendingId,'Recovery?')
  await repository.finish(first.turn,'Stale answer',false,'completed')
  assert.equal((await repository.get(user.id,id)).turns.at(-1).answer,null)
  await repository.finish(retry.turn,'Retried answer',false,'completed')
  assert.equal((await repository.get(user.id,id)).turns.length,3)

  process.env.JWT_SECRET = 'isolated-http-test-secret'
  const app = express()
  app.use('/api/chat',createChatRouter(new ChatService({generate:async()=>({content:'HTTP answer',truncated:false})}),repository))
  const server = await new Promise(resolve=>{const s=app.listen(0,'127.0.0.1',()=>resolve(s))})
  t.after(()=>{server.closeAllConnections();return new Promise(resolve=>server.close(resolve))})
  const base = `http://127.0.0.1:${server.address().port}/api/chat/conversations`
  const headers = {'Content-Type':'application/json',Authorization:`Bearer ${jwt.sign({id:user.id,email:user.email,role:'ADMIN'},process.env.JWT_SECRET)}`}
  assert.equal((await fetch(base)).status,401)
  const list = await fetch(base,{headers})
  assert.equal(list.status,200)
  assert.equal(list.headers.get('cache-control'),'no-store')
  assert.equal((await list.json()).data.length,1)
  const post = body=>fetch(`${base}/${id}/messages`,{method:'POST',headers,body:JSON.stringify(body)})
  assert.equal((await post({requestId:randomUUID(),message:'Hi',mode:'general'})).status,400)
  assert.equal((await post({requestId:randomUUID(),message:'x'.repeat(18000)})).status,413)
  const response = await post({requestId:randomUUID(),message:'HTTP question'})
  assert.equal(response.status,200)
  const data = (await response.json()).data
  assert.equal(data.turns.at(-1).answer,'HTTP answer')
  assert.equal(data.userId,undefined)
  assert.equal(data.turns[0].attemptId,undefined)
  await repository.delete(user.id,id)
  assert.equal(await db.chatTurn.count({where:{conversationId:id}}),0)
})
